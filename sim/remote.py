"""Run StormSim storms off the touko-agents box: Daytona sandboxes, overflowing to the Fly.io pool (via `drun`).

    from sim.remote import run_storm_remote
    rd = run_storm_remote("elnino_ar_2026", plan_code=None, label="baseline")   # -> Path(runs/<run_id>/)

Stages a minimal job dir in /tmp/stormsim-jobs/<run_id>/ (sim/*.py, data/grid inputs + cached wind fields,
data/reference, streets, pinned wind map, baseline result for the BCA, plan code / sandbox export), runs
`drun --setup <uv venv py3.12 + pinned wheels> -- python _remote_job.py` (4 vCPU / 8 GiB), then moves the fetched
runs/<run_id>/ into the repo's runs/. Same code + inputs + pinned versions -> same ledger_hash as a local run.

Env: STORMSIM_REMOTE_MAX (concurrent remote runs per process, default 12), DRUN_BACKEND=daytona|fly (forces a side),
STORMSIM_REMOTE_KEEP_JOBS=1 (keep /tmp job dirs). agent/runner.py routes here when STORMSIM_REMOTE=1.
"""
from __future__ import annotations

import json
import os
import re
import shutil
import subprocess
import threading
import time
import uuid
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
RUNS = ROOT / "runs"
GRID = ROOT / "data" / "grid"
JOBS = Path(os.environ.get("STORMSIM_REMOTE_JOBS", "/tmp/stormsim-jobs"))
DRUN = shutil.which("drun") or os.path.expanduser("~/.local/bin/drun")
_SEM = threading.BoundedSemaphore(max(1, int(os.environ.get("STORMSIM_REMOTE_MAX", "12"))))

# Pinned to the local .venv (uv pip freeze, 25.10) so remote numerics match local runs.
REQUIREMENTS = """numpy==2.5.4
scipy==1.18.1
numba==0.68.0
llvmlite==0.50.0
shapely==2.2.0
pyproj==3.8.0
matplotlib==3.11.2
pillow==13.0.0
imageio==2.38.1
imageio-ffmpeg==0.6.0
"""
PY = "3.12"   # local .venv is 3.12.15; sandbox images ship 3.14
VENV = "/tmp/sv"
SETUP = (f"echo @@T setup0 $(date +%s.%N) && export UV_CACHE_DIR=/tmp/uvc UV_PYTHON_INSTALL_DIR=/tmp/uvpy && "
         f"uv venv -q -p {PY} {VENV} && uv pip install -q --python {VENV}/bin/python -r requirements.txt && "
         f"echo @@T setup1 $(date +%s.%N)")
# Same float results on every host: the box (EPYC 7543, AVX2) and Fly (AVX2) vs Daytona (EPYC 9254, AVX-512).
# numpy's AVX-512 (X86_V4) kernels round differently from its AVX2 ones; turn them off so every host runs the
# AVX2 kernels the box uses. STORMSIM_REMOTE_NUMBA_CPU (e.g. znver3 = the box) pins numba's LLVM target too.
CPU_ENV = {"NPY_DISABLE_CPU_FEATURES": "X86_V4 AVX512_ICL AVX512_SPR"}
if os.environ.get("STORMSIM_REMOTE_NUMBA_CPU"):
    CPU_ENV["NUMBA_CPU_NAME"] = os.environ["STORMSIM_REMOTE_NUMBA_CPU"]
GRID_FILES = ("meta.json", "city.npz", "buildings.json", "trees.json", "cars.json", "inlets.json", "validation.json")

JOB_SCRIPT = r'''# generated by sim/remote.py: runs one storm in the sandbox with the same code path as a local run
import json, os, sys, time
sys.path.insert(0, os.getcwd())
cfg = json.load(open("job.json"))
print("@@T run0", time.time(), flush=True)
from sim.run import run_storm, ledger_hash  # noqa: E402
code = open("plan.py").read() if os.path.exists("plan.py") else None
rd = run_storm(cfg["storm"], plan_code=code, label=cfg["label"], plan_dir=cfg.get("plan_dir"), run_id=cfg["run_id"],
               render=cfg["render"], threads=cfg["threads"], verbose=True, water_cache=False, **cfg.get("kw", {}))
r = json.load(open(os.path.join(rd, "result.json")))
print("@@LEDGER", r["ledger_hash"], flush=True)
print("@@T run1", time.time(), flush=True)
'''


class RemoteRunError(RuntimeError):
    pass


def _new_run_id(label: str) -> str:   # same format as sim.run._new_run_id
    tag = "".join(c if c.isalnum() else "-" for c in (label or "run").lower())[:24].strip("-") or "run"
    return f"{time.strftime('%Y%m%d-%H%M%S')}-{uuid.uuid4().hex[:4]}-{tag}"


def _cp(src: Path, dst: Path):
    dst.parent.mkdir(parents=True, exist_ok=True)
    shutil.copy2(src, dst)   # copies, never hardlinks: drun's fetch writes into the job dir


def stage_job(job: Path, storm: str, plan_code, label, run_id, render, threads, plan_dir=None, kw=None) -> dict:
    """Write the minimal job dir. Returns info about what was staged."""
    if job.exists():
        shutil.rmtree(job)
    job.mkdir(parents=True)
    for p in sorted((ROOT / "sim").glob("*.py")) + sorted((ROOT / "sim").glob("*.md")):
        _cp(p, job / "sim" / p.name)
    for name in ("__init__.py", "citylib.py"):   # sim.run loads sandbox exports via agent.citylib
        if (ROOT / "agent" / name).exists():
            _cp(ROOT / "agent" / name, job / "agent" / name)
    for name in GRID_FILES:
        if (GRID / name).exists():
            _cp(GRID / name, job / "data" / "grid" / name)
    winds = sorted(GRID.glob("wind_*.npz"))
    for p in winds:
        _cp(p, job / "data" / "grid" / p.name)
    for p in (ROOT / "data" / "reference").rglob("*"):
        if p.is_file() and p.suffix != ".pdf" and "__pycache__" not in p.parts:
            _cp(p, job / p.relative_to(ROOT))
    for rel in ("data/raw/extra/streets.geojson", "data/raw/nws_alerts_now.json"):
        if (ROOT / rel).exists():
            _cp(ROOT / rel, job / rel)
    # wind pins -> paths relative to the job dir (sim.run resolves them against the cwd)
    pins_p = RUNS / "_wind_pins.json"
    jr = job / "runs"
    jr.mkdir(parents=True, exist_ok=True)
    if pins_p.exists():
        try:
            pins = json.loads(pins_p.read_text())
            out = {}
            for k, v in pins.items():
                if (job / "data" / "grid" / Path(v).name).exists():
                    out[k] = f"data/grid/{Path(v).name}"
            (jr / "_wind_pins.json").write_text(json.dumps(out, indent=1))
        except Exception:
            pass
    # baseline index + baseline result (BCA of plan runs needs its total)
    has_plan = bool(plan_code and plan_code.strip()) or bool(plan_dir)
    base_p = RUNS / "_baselines.json"
    if has_plan and base_p.exists():
        try:
            idx = json.loads(base_p.read_text())
            rid = idx.get(storm)
            if rid and (RUNS / rid / "result.json").exists():
                (jr / "_baselines.json").write_text(json.dumps({storm: rid}))
                _cp(RUNS / rid / "result.json", jr / rid / "result.json")
        except Exception:
            pass
    if plan_code and plan_code.strip():
        (job / "plan.py").write_text(plan_code)
    jpd = None
    if plan_dir and Path(plan_dir).is_dir():
        for p in Path(plan_dir).iterdir():
            if p.is_file():
                _cp(p, job / "plan_export" / p.name)
        jpd = "plan_export"
    (job / "requirements.txt").write_text(REQUIREMENTS)
    (job / "_remote_job.py").write_text(JOB_SCRIPT)
    (job / "job.json").write_text(json.dumps({"storm": storm, "label": label, "run_id": run_id, "render": bool(render),
                                              "threads": int(threads), "plan_dir": jpd, "kw": kw or {}}))
    size = sum(p.stat().st_size for p in job.rglob("*") if p.is_file())
    return {"bytes": size, "wind_fields": [p.name for p in winds]}


def run_storm_remote(storm: str, plan_code: str | None = None, label: str = "run", render: bool = False,
                     threads: int = 4, plan_dir: str | None = None, run_id: str | None = None,
                     backend: str | None = None, timeout_s: float = 3600, cpu_env: dict | None = None,
                     **kw) -> Path:
    """Simulate one storm on a remote 4 vCPU sandbox. Returns the local run dir (runs/<run_id>/).
    Extra kwargs (e.g. max_duration_s, seed_key) go to sim.run.run_storm. Raises RemoteRunError on failure."""
    run_id = run_id or _new_run_id(label)
    job = JOBS / run_id
    t = {"queued": time.time()}
    with _SEM:
        t["start"] = time.time()
        info = stage_job(job, storm, plan_code, label, run_id, render, threads, plan_dir, kw)
        t["staged"] = time.time()
        cenv = CPU_ENV if cpu_env is None else cpu_env
        pre = "".join(f"{k}='{v}' " for k, v in cenv.items())
        cmd = (f"echo @@T cmd0 $(date +%s.%N) && {pre}NUMBA_NUM_THREADS={int(threads)} STORMSIM_WATER_THREADS={int(threads)} "
               f"OMP_NUM_THREADS=1 MPLBACKEND=Agg {VENV}/bin/python _remote_job.py")
        env = dict(os.environ)
        if backend:
            env["DRUN_BACKEND"] = backend
        argv = ["nice", "-n", "10", DRUN, "--setup", SETUP, "--", cmd]
        log_lines, marks, ledger = [], {}, None
        first_out = exit_at = None
        proc = subprocess.Popen(argv, cwd=job, env=env, stdout=subprocess.PIPE, stderr=subprocess.STDOUT,
                                text=True, bufsize=1, start_new_session=True)
        killer = threading.Timer(timeout_s, lambda: proc.kill())
        killer.start()
        logf = open(job / "drun.log", "w")
        try:
            for line in proc.stdout:
                now = time.time()
                log_lines.append(line)
                logf.write(line)
                logf.flush()
                m = re.search(r"@@T (\w+) ([\d.]+)", line)   # Daytona prefixes \x01 stream bytes
                if m:
                    marks[m.group(1)] = float(m.group(2))
                    if first_out is None:
                        first_out = now
                elif "@@LEDGER" in line:
                    ledger = line.split("@@LEDGER", 1)[1].split()[0]
                elif re.match(r"drun: exit -?\d+", line):
                    exit_at = now
            rc = proc.wait()
        finally:
            killer.cancel()
            logf.close()
        t["done"] = time.time()
    text = "".join(log_lines)
    be = "fly" if "Fly machine" in text else ("daytona" if "drun: sandbox" in text else "?")
    src = job / "runs" / run_id
    if rc != 0 or not (src / "result.json").exists():
        tail = "".join(log_lines[-25:])
        raise RemoteRunError(f"remote run {run_id} failed (rc={rc}, backend={be}); job dir {job}\n{tail}")
    phases = {
        "queue_s": t["start"] - t["queued"],
        "stage_s": t["staged"] - t["start"],
        "acquire_upload_s": (first_out - t["staged"]) if first_out else None,
        "setup_s": marks["setup1"] - marks["setup0"] if {"setup0", "setup1"} <= marks.keys() else None,
        "run_s": marks["run1"] - marks["cmd0"] if {"cmd0", "run1"} <= marks.keys() else None,
        "fetch_s": (t["done"] - exit_at) if exit_at else None,
        "total_s": t["done"] - t["queued"],
    }
    phases = {k: (round(v, 1) if isinstance(v, float) else v) for k, v in phases.items()}
    dst = RUNS / run_id
    if dst.exists():
        shutil.rmtree(dst)
    shutil.move(str(src), str(dst))
    try:   # annotate (ledger_hash is over the ledger only, so this does not change it)
        rp = dst / "result.json"
        r = json.loads(rp.read_text())
        w = r.get("wind") or {}
        if w.get("path"):
            w["path"] = str(GRID / Path(w["path"]).name)
        r["remote"] = {"backend": be, "threads": int(threads), "python": PY, "cpu_env": cenv, "phases_s": phases,
                       "upload_mb": round(info["bytes"] / 1e6, 1)}
        rp.write_text(json.dumps(r, indent=1, default=str))
    except Exception:
        pass
    if os.environ.get("STORMSIM_REMOTE_KEEP_JOBS") != "1":
        shutil.rmtree(job, ignore_errors=True)
    return dst


if __name__ == "__main__":
    import argparse
    ap = argparse.ArgumentParser(description="run one storm remotely (drun: Daytona, Fly overflow)")
    ap.add_argument("storm", nargs="?", default="elnino_ar_2026")
    ap.add_argument("--plan", default=None)
    ap.add_argument("--label", default="remote")
    ap.add_argument("--render", action="store_true")
    ap.add_argument("--threads", type=int, default=4)
    ap.add_argument("--backend", default=None, choices=[None, "daytona", "fly"])
    ap.add_argument("--max-duration-s", type=float, default=None)
    a = ap.parse_args()
    code = Path(a.plan).read_text() if a.plan else None
    extra = {"max_duration_s": a.max_duration_s} if a.max_duration_s else {}
    t0 = time.time()
    rd = run_storm_remote(a.storm, plan_code=code, label=a.label, render=a.render, threads=a.threads,
                          backend=a.backend, **extra)
    r = json.loads((rd / "result.json").read_text())
    print(json.dumps({"run_dir": str(rd), "ledger_hash": r["ledger_hash"], "total_usd": r["ledger"]["total_usd"],
                      "remote": r.get("remote"), "wall_s": round(time.time() - t0, 1)}))
